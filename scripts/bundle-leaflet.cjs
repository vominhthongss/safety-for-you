/**
 * Bundle Leaflet JS/CSS into the React Native JS bundle so the map engine
 * does not depend on a third-party CDN at runtime. GSI tiles still need internet.
 * Runs automatically on npm install / npm ci.
 */
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const leafletRoot = path.dirname(require.resolve("leaflet/package.json"));
const jsPath = path.join(leafletRoot, "dist", "leaflet.js");
const cssPath = path.join(leafletRoot, "dist", "leaflet.css");
const destination = path.join(root, "src", "generated", "leafletAssets.js");
const js = fs.readFileSync(jsPath, "utf8");
const css = fs.readFileSync(cssPath, "utf8");
if (!js.includes("L.") && !js.includes("Leaflet")) {
  throw new Error("Leaflet vendor bundle is missing");
}
fs.mkdirSync(path.dirname(destination), { recursive:true });
const contents = [
  "// Generated from the pinned leaflet npm package by scripts/bundle-leaflet.cjs.",
  "// Do not edit this file manually. Re-run npm install to regenerate.",
  "export const LEAFLET_JS = " + JSON.stringify(js) + ";",
  "export const LEAFLET_CSS = " + JSON.stringify(css) + ";",
  ""
].join("\n");
fs.writeFileSync(destination, contents, "utf8");
console.log("Bundled Leaflet " + js.length + " JS bytes and " + css.length + " CSS bytes");
